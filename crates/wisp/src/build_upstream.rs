//! Stage upstream bindings from the selected WIT world without source inference.
use super::{world_text, write};
use anyhow::{Context, Result, ensure};
use heck::ToSnakeCase;
use std::path::Path;
use wit_parser::{Resolve, WorldId};

pub fn clang(
    resolve: &Resolve,
    world: WorldId,
    cpp: bool,
    sources: &[String],
    directory: &Path,
) -> Result<(String, Vec<String>)> {
    let language = if cpp { "cpp" } else { "c" };
    let files = crate::generator_tools::wit_bindgen(resolve, world, language, &[])?;
    let mut generated_sources = Vec::new();
    let mut objects = Vec::new();
    for (name, bytes) in files {
        if name.ends_with(".o") {
            objects.push(name.clone());
        }
        if name.ends_with(".cpp") || name.ends_with(".c") {
            generated_sources.push(name.clone());
        }
        write(directory.join(name), bytes)?;
    }
    ensure!(
        !generated_sources.is_empty(),
        "upstream C/C++ binding source missing"
    );
    let mut unit = String::new();
    // Include generated declarations before implementations supplied by the project.
    let header = format!(
        "{}{}.h",
        resolve.worlds[world].name.to_snake_case(),
        if cpp { "_cpp" } else { "" }
    );
    unit.push_str(&format!("#include {header:?}\n"));
    for source in sources {
        unit.push_str(&format!("#include {source:?}\n"));
    }
    for source in generated_sources {
        unit.push_str(&format!("#include {source:?}\n"));
    }
    Ok((unit, objects))
}

pub fn go(resolve: &Resolve, world: WorldId, source: &Path) -> Result<()> {
    let module = crate::build_go::module_prefix(source)?;
    let files = crate::library_go::guest::upstream::generate(
        &world_text(resolve, world)?,
        &resolve.worlds[world].name,
        &module,
    )?;
    let has_exports = files.keys().any(|path| path.starts_with("wit_exports/"));
    for (name, bytes) in files {
        write(source.join(name), bytes)?;
    }
    let mut root = String::from("// Generated by Wisp.\npackage main\n");
    if has_exports {
        root.push_str(&format!(
            "import _ {path:?}\n",
            path = format!("{module}/wit_exports")
        ));
    }
    write(source.join("wisp_main.go"), root)
}

pub fn rust(resolve: &Resolve, world: WorldId, source: &Path) -> Result<()> {
    let files = crate::generator_tools::wit_bindgen(
        resolve,
        world,
        "rust",
        &[
            "--runtime-path",
            "crate::wisp_bindings::__wisp_rt",
            "--generate-all",
        ],
    )?;
    let name = format!("{}.rs", resolve.worlds[world].name.to_snake_case());
    let generated = files
        .get(&name)
        .context("upstream Rust binding source missing")?;
    let runtime = include_str!("../assets/upstream-wit-runtime.rs");
    let mut output = format!(
        "// Generated by Wisp and wit-bindgen 0.61.1.\npub mod __wisp_rt {{\n{runtime}\n}}\n"
    )
    .into_bytes();
    output.extend_from_slice(generated);
    let project = crate::build_rust::project(source)?;
    let directory = project.source.parent().context("Rust source parent")?;
    write(directory.join("wisp_bindings.rs"), output)
}
