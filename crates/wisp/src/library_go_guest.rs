//! Ordinary Go modules whose calls become Component imports on wasip1/wasm.
use anyhow::{Context, Result, bail, ensure};
use heck::ToUpperCamelCase;
use serde_json::{Value, json};
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};
use wit_parser::{FunctionKind, Resolve, Type, TypeDefKind, WorldId, WorldItem};

pub const PLATFORM: &str = "wasip1_wasm";

fn scalar(resolve: &Resolve, ty: Type, depth: usize) -> Result<(&'static str, &'static str)> {
    ensure!(depth < 32, "Go guest alias depth limit");
    Ok(match ty {
        Type::Bool => ("bool", "int32"),
        Type::U8 => ("uint8", "uint32"),
        Type::U16 => ("uint16", "uint32"),
        Type::U32 => ("uint32", "uint32"),
        Type::U64 => ("uint64", "uint64"),
        Type::S8 => ("int8", "int32"),
        Type::S16 => ("int16", "int32"),
        Type::S32 => ("int32", "int32"),
        Type::S64 => ("int64", "int64"),
        Type::F32 => ("float32", "float32"),
        Type::F64 => ("float64", "float64"),
        Type::Id(id) => match resolve.types[id].kind {
            TypeDefKind::Type(ty) => return scalar(resolve, ty, depth + 1),
            _ => bail!("unsupported Go guest binding: only scalar types and aliases are supported"),
        },
        _ => bail!("unsupported Go guest binding: only scalar types and aliases are supported"),
    })
}
fn convert(ty: (&str, &str), value: &str, lower: bool) -> String {
    if ty.0 == "bool" {
        if lower {
            format!("wispBool({value})")
        } else {
            format!("({value} != 0)")
        }
    } else {
        format!("{}({value})", if lower { ty.1 } else { ty.0 })
    }
}
pub(super) fn bindings(resolve: &Resolve, world: WorldId) -> Result<String> {
    let reactor = crate::library_wasi::reactor_host(resolve, world)?;
    let world = &resolve.worlds[world];
    ensure!(
        world
            .imports
            .values()
            .all(|item| matches!(item, WorldItem::Type { .. }))
            || reactor,
        "Go scalar modules require a closed Component or supported WASI reactor imports"
    );
    let mut code = String::from(
        "// Code generated by wisp. DO NOT EDIT.\n//go:build wasip1 && wasm\n\npackage component\n\nfunc wispBool(value bool) int32 { if value { return 1 }; return 0 }\n\n",
    );
    let mut names = BTreeSet::new();
    let mut ordinal = 0;
    for (key, item) in &world.exports {
        let module = resolve.name_world_key(key);
        let (prefix, functions) = match item {
            WorldItem::Function(f) => (String::new(), vec![f]),
            WorldItem::Interface { id, .. } => {
                let interface = &resolve.interfaces[*id];
                (
                    if interface.name.as_deref() == Some("api") && world.exports.len() == 1 {
                        String::new()
                    } else {
                        interface
                            .name
                            .as_deref()
                            .context("Go guest interface name")?
                            .to_upper_camel_case()
                    },
                    interface.functions.values().collect(),
                )
            }
            WorldItem::Type { .. } => continue,
        };
        for f in functions {
            ensure!(
                matches!(f.kind, FunctionKind::Freestanding) && f.params.len() <= 16,
                "unsupported Go guest function"
            );
            let name = format!("{prefix}{}", f.name.to_upper_camel_case());
            ensure!(
                names.insert(name.clone()),
                "Go guest binding name collision"
            );
            let params = f
                .params
                .iter()
                .map(|p| scalar(resolve, p.ty, 0))
                .collect::<Result<Vec<_>>>()?;
            let result = f.result.map(|t| scalar(resolve, t, 0)).transpose()?;
            let signature = |abi: bool| {
                params
                    .iter()
                    .enumerate()
                    .map(|(i, t)| format!("a{i} {}", if abi { t.1 } else { t.0 }))
                    .collect::<Vec<_>>()
                    .join(", ")
            };
            let result_ty = |abi: bool| {
                result
                    .map(|t| format!(" {}", if abi { t.1 } else { t.0 }))
                    .unwrap_or_default()
            };
            let args = params
                .iter()
                .enumerate()
                .map(|(i, t)| convert(*t, &format!("a{i}"), true))
                .collect::<Vec<_>>()
                .join(", ");
            let module = if matches!(item, WorldItem::Function(_)) {
                "$root"
            } else {
                &module
            };
            code.push_str(&format!(
                "//go:wasmimport {module} {}\nfunc wispImport{ordinal}({}){}\n\n",
                f.name,
                signature(true),
                result_ty(true)
            ));
            let call = format!("wispImport{ordinal}({args})");
            let body = result
                .map(|t| format!("return {}", convert(t, &call, false)))
                .unwrap_or(call);
            code.push_str(&format!(
                "func {name}({}){} {{\n    {body}\n}}\n\n",
                signature(false),
                result_ty(false)
            ));
            ordinal += 1;
        }
    }
    ensure!(
        ordinal > 0 && ordinal <= 1024,
        "Go guest function count limit"
    );
    Ok(code)
}

pub fn files(
    component: &[u8],
    module: &str,
    version: &str,
    notices: &BTreeMap<String, Vec<u8>>,
) -> Result<BTreeMap<String, Vec<u8>>> {
    super::validate_module(module, version)?;
    let (resolve, world) = super::decode_component(component)?;
    super::validate_type_expansion(&resolve, world)?;
    let package = resolve.worlds[world]
        .package
        .context("Go guest world package")?;
    let others = resolve
        .packages
        .iter()
        .map(|(id, _)| id)
        .filter(|id| *id != package)
        .collect::<Vec<_>>();
    let mut printer = wit_component::WitPrinter::default();
    printer.print(&resolve, package, &others)?;
    let descriptor = json!({"schema":1,"kind":"wisp-go-component-guest","module":module,"version":version,
        "component":{"path":"component.wasm","sha256":super::digest(component)},"platform":PLATFORM});
    let (mod_file, _) = super::module_metadata(module, version)?;
    let mut files = BTreeMap::from([
        ("go.mod".into(), mod_file),
        (
            "bindings_wasip1.go".into(),
            bindings(&resolve, world)?.into_bytes(),
        ),
        ("component.wasm".into(), component.to_vec()),
        (
            "component.wit".into(),
            printer.output.to_string().into_bytes(),
        ),
        (
            "wisp-component.json".into(),
            serde_json::to_vec_pretty(&descriptor)?,
        ),
    ]);
    let mut size = 0;
    ensure!(notices.len() <= 17, "Go guest notice count limit");
    for (name, bytes) in notices {
        ensure!(
            !name.is_empty()
                && name.len() <= 240
                && !name.contains('\\')
                && name
                    .split('/')
                    .all(|p| !p.is_empty() && p != "." && p != ".."),
            "unsafe Go guest notice path"
        );
        ensure!(
            (name == "WISP-NOTICES.txt" || name.starts_with("notices/")) && !name.ends_with(".go"),
            "invalid Go guest notice"
        );
        size += bytes.len();
        ensure!(
            bytes.len() <= 256 * 1024 && size <= 1024 * 1024,
            "Go guest notice size limit"
        );
        ensure!(
            files.insert(name.clone(), bytes.clone()).is_none(),
            "Go guest notice collision"
        );
    }
    Ok(files)
}
#[allow(dead_code)]
pub fn generate(
    component: &[u8],
    output: &Path,
    module: &str,
    version: &str,
    notices: &BTreeMap<String, Vec<u8>>,
) -> Result<()> {
    ensure!(!output.try_exists()?, "Go guest output already exists");
    for (path, bytes) in files(component, module, version, notices)? {
        let path = output.join(path);
        fs::create_dir_all(path.parent().context("Go guest parent")?)?;
        fs::write(path, bytes)?;
    }
    Ok(())
}
pub fn verify_archive(
    component: &[u8],
    module: &str,
    version: &str,
    bytes: &[u8],
    notices: &BTreeMap<String, Vec<u8>>,
) -> Result<Value> {
    let temp = super::unpack_module_archive(bytes, module, version)?;
    let mut actual = BTreeMap::new();
    super::package_files(
        temp.path(),
        temp.path(),
        &mut actual,
        &mut (32 * 1024 * 1024),
    )?;
    ensure!(
        actual == files(component, module, version, notices)?,
        "Go guest generated package differs"
    );
    ensure!(
        super::module_archive(temp.path(), module, version)?.zip == bytes,
        "Go guest module archive is not canonical"
    );
    Ok(json!({"platform":PLATFORM}))
}
/// go mod vendor strips go.mod and can omit notice subdirectories. Authenticate
/// every executable/binding input retained by the normal Go module installer.
pub fn vendored(directory: &Path, module: &str) -> Result<Value> {
    let descriptor: Value =
        serde_json::from_slice(&read(&directory.join("wisp-component.json"), 1024 * 1024)?)?;
    let version = descriptor["version"]
        .as_str()
        .context("Go guest module version")?;
    super::validate_module(module, version)?;
    let component = read(&directory.join("component.wasm"), 16 * 1024 * 1024)?;
    let portable = descriptor["platform"] == super::portable::PLATFORM;
    let expected_files = if portable {
        super::portable::files(&component, module, version, &BTreeMap::new())?
    } else {
        files(&component, module, version, &BTreeMap::new())?
    };
    let expected_names = expected_files.keys().cloned().collect::<BTreeSet<_>>();
    for (name, expected) in expected_files {
        if name == "go.mod" || name == "go.sum" {
            continue;
        }
        ensure!(
            read(&directory.join(&name), 32 * 1024 * 1024)? == expected,
            "vendored Go guest package differs: {name}"
        );
    }
    fn inspect_tree(root: &Path, directory: &Path, expected: &BTreeSet<String>) -> Result<()> {
        for entry in fs::read_dir(directory)? {
            let entry = entry?;
            ensure!(
                !entry.file_type()?.is_symlink(),
                "symlink in vendored Go package"
            );
            let path = entry.path();
            if entry.file_type()?.is_dir() {
                inspect_tree(root, &path, expected)?;
                continue;
            }
            let name = path
                .strip_prefix(root)?
                .to_str()
                .context("Go filename")?
                .replace('\\', "/");
            if matches!(
                path.extension().and_then(|s| s.to_str()),
                Some("go" | "h" | "c" | "cc" | "cpp" | "cxx" | "s" | "S")
            ) {
                ensure!(
                    expected.contains(&name),
                    "unexpected Go package source: {name}"
                );
            }
        }
        Ok(())
    }
    inspect_tree(directory, directory, &expected_names)?;
    Ok(descriptor)
}
fn read(path: &Path, limit: u64) -> Result<Vec<u8>> {
    let meta = fs::symlink_metadata(path)?;
    ensure!(
        meta.is_file() && meta.len() <= limit,
        "invalid Go guest input"
    );
    Ok(fs::read(path)?)
}
