import assert from "node:assert/strict";
import { counters, warehouse } from "@wisp/resource-library";

const left = new counters.Counter(10);
assert.equal(left.add(2), 12);
const right = counters.make(30);
const merged = counters.Counter.combine(left, right);
assert.equal(merged.value(), 42);
assert.equal(counters.dropped(), 1);
assert.throws(() => right.value());
assert.throws(() => counters.checked(0));
const checked = counters.checked(8);
assert.equal(checked.value(), 8);
checked[Symbol.dispose]();
assert.equal(counters.dropped(), 2);
merged[Symbol.dispose]();
assert.throws(() => merged.value());
left[Symbol.dispose]();
const bundle = warehouse.echoBundle(warehouse.makeBundle(20));
assert.equal(warehouse.sum({ first: bundle.primary, rest: bundle.others }), 63);
const optional = warehouse.echoOption(bundle.optional);
assert.equal(optional.value(), 23);
optional[Symbol.dispose]();
const values = warehouse.echoList(bundle.others);
assert.equal(values[0].value() + values[1].value(), 43);
for (const value of values) value[Symbol.dispose]();
const selected = warehouse.echoChoice({ tag: "selected", val: bundle.primary });
assert.equal(selected.val.value(), 20);
selected.val[Symbol.dispose]();
console.log("resources-node-passed");
