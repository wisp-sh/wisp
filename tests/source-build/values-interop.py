#!/usr/bin/env python3
"""Build C++ and Rust consumers of an installed rich Component and execute them."""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
snapshot_spec = importlib.util.spec_from_file_location("source_build_snapshot", ROOT / "tests/source-build/snapshot.py")
snapshot_module = importlib.util.module_from_spec(snapshot_spec)
snapshot_spec.loader.exec_module(snapshot_module)


def run(command, *, cwd=None):
    process = subprocess.run([str(value) for value in command], cwd=cwd, text=True, capture_output=True)
    if process.returncode:
        raise RuntimeError(f"{command}\n{process.stdout}\n{process.stderr}")
    return process.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release", type=Path, required=True, help="Admitted Go values provider release")
    parser.add_argument("--cli", type=Path, default=ROOT / "target/debug/wisp")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--cache", type=Path, default=ROOT / ".tools/build/runtime-cache")
    parser.add_argument("--case", action="append", choices=["cpp", "rust"])
    args = parser.parse_args()
    cli = args.cli.resolve()
    release = args.release.resolve()
    cache = args.cache.resolve()
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=False)
    snapshot = output / "wisp"
    snapshot_module.freeze_cli(cli, snapshot)
    cli = snapshot
    run([cli, "library", "validate", release])
    manifest = json.loads((release / "library-release.json").read_text())
    records = []
    for case in args.case or ["cpp", "rust"]:
        print(f"Building rich {case} consumer", flush=True)
        project = output / f"{case}-source"
        project.mkdir()
        if case == "cpp":
            provider = project / "deps/provider"
            shutil.copytree(release, provider)
            (project / "main.cpp").write_text(CPP)
            dependency = (
                "\n[dependencies.provider]\n"
                f"package = {json.dumps(manifest['identity'])}\n"
                f"version = {json.dumps(manifest['version'])}\n"
                'path = "deps/provider"\n'
            )
            build = '[build]\ncompiler = "clang"\nsources = ["main.cpp"]\n'
        else:
            crate = project / "rust"
            (crate / "src").mkdir(parents=True)
            guest = crate / "deps/provider"
            run([cli, "library", "rust-guest", release, "--out", guest])
            import tomllib
            guest_manifest = tomllib.loads((guest / "Cargo.toml").read_text())
            (crate / "Cargo.toml").write_text(
                '[package]\nname = "rich-values-consumer"\nversion = "0.1.0"\nedition = "2021"\n'
                '[dependencies.provider]\n'
                f"package = {json.dumps(guest_manifest['package']['name'])}\n"
                f"version = {json.dumps('=' + guest_manifest['package']['version'])}\n"
                'path = "deps/provider"\n[workspace]\n'
            )
            (crate / "Cargo.lock").write_text(
                "# This file is automatically @generated by Cargo.\nversion = 4\n\n"
                '[[package]]\nname = "rich-values-consumer"\nversion = "0.1.0"\n'
                f"dependencies = [{json.dumps(guest_manifest['package']['name'])}]\n\n"
                f"[[package]]\nname = {json.dumps(guest_manifest['package']['name'])}\n"
                f"version = {json.dumps(guest_manifest['package']['version'])}\n"
            )
            (crate / "src/lib.rs").write_text(RUST)
            dependency = ""
            build = '[build]\ncompiler = "rust"\nproject = "rust"\n'
        (project / "wisp.toml").write_text(
            f'[package]\nname = "test:{case}-values-import"\nversion = "0.1.0"\n'
            '[metadata]\nlicense = "MIT"\ndescription = "Installed rich Component consumer"\n'
            + dependency + "\n" + build
        )
        destination = output / f"{case}-release"
        run([cli, "build", project, "--out", destination, "--cache", cache])
        run([cli, "library", "validate", destination])
        consumer = output / f"{case}-node"
        consumer.mkdir()
        (consumer / "package.json").write_text('{"private":true,"type":"module"}\n')
        run(["npm", "install", "--offline", "--ignore-scripts", "--no-audit", "--no-fund", destination / "node.tgz"], cwd=consumer)
        package = json.loads((destination / "library-release.json").read_text())["packages"]["node"]["name"]
        (consumer / "check.mjs").write_text(
            "import assert from 'node:assert/strict';\nimport {api} from " + json.dumps(package) + ";\n"
            "for(let i=0;i<3;i++) assert.equal(api.score(),42);\nconsole.log('rich-imports-ok');\n"
        )
        result = run([os.environ.get("WISP_NODE", "node"), "check.mjs"], cwd=consumer).strip()
        if result != "rich-imports-ok":
            raise RuntimeError(result)
        receipt = json.loads((destination / "build/build.json").read_text())
        records.append({"language": case, "result": result, "componentSha256": receipt["componentSha256"], "tools": receipt["tools"], "receipt": str(destination / "build/build.json")})
    result = {"passed": True, "providerSha256": manifest["componentSha256"], "cliSha256": hashlib.sha256(cli.read_bytes()).hexdigest(), "cases": records}
    (output / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


CPP = r'''
#include "provider.hpp"

static bool equal(wisp::string value, wisp::string expected) {
    if (value.size != expected.size) return false;
    for (unsigned i=0; i<value.size; ++i) if (value.data[i] != expected.data[i]) return false;
    return true;
}
static bool packet_ok(provider::WispPacket value) {
    return equal(value.label,wisp::string{"hello 🦀"}) && value.data.size == 3 &&
        value.data.data[0] == 0 && value.data.data[1] == 128 && value.data.data[2] == 255 &&
        value.sequence == 9007199254740994ULL && value.enabled;
}
unsigned score() {
    auto saved = provider::echo(wisp::string{"persistent 🦀"});
    auto copied = saved;
    saved = provider::echo(wisp::string{"replacement"});
    for (unsigned i=0; i<1000; ++i) {
        if (!equal(provider::echo(wisp::string{""}),wisp::string{""})) return 1;
        if (!equal(provider::echo(wisp::string{"hello 🦀 世界"}),wisp::string{"hello 🦀 世界"})) return 2;
        unsigned char data[3] = {0,128,255};
        auto bytes = provider::buffer(wisp::bytes{data,3});
        if (bytes.size != 3 || bytes.data[0] != 0 || bytes.data[1] != 128 || bytes.data[2] != 255) return 3;
        auto ok = provider::checked(true);
        if (ok.is_err || !packet_ok(ok.ok)) return 4;
        auto echoed = provider::packet_value(ok.ok);
        if (!packet_ok(echoed)) return 5;
        auto denied = provider::checked(false);
        if (!denied.is_err || !equal(denied.err,wisp::string{"denied"})) return 6;
        if (!equal(copied,wisp::string{"persistent 🦀"}) || !equal(saved,wisp::string{"replacement"})) return 7;
    }
    return 42;
}
'''

RUST = r'''
fn packet_ok(value: &provider::WispPacket) -> bool {
    value.label == "hello 🦀" && value.data == [0,128,255] &&
        value.sequence == 9007199254740994 && value.enabled
}
pub fn score() -> u32 {
    let saved = provider::echo("persistent 🦀".to_owned());
    for _ in 0..1000 {
        if provider::echo(String::new()) != "" { return 1; }
        if provider::echo("hello 🦀 世界".to_owned()) != "hello 🦀 世界" { return 2; }
        if provider::buffer(vec![0,128,255]) != [0,128,255] { return 3; }
        let ok = match provider::checked(true) { Ok(value) => value, Err(_) => return 4 };
        if !packet_ok(&ok) { return 5; }
        if !packet_ok(&provider::packet_value(ok)) { return 6; }
        match provider::checked(false) { Err(message) if message == "denied" => {}, _ => return 7 }
        if saved != "persistent 🦀" { return 8; }
    }
    42
}
'''

if __name__ == "__main__":
    main()
